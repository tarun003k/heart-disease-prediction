@app.route('/predict', methods=['POST'])
def predict():
    if model is None or scaler is None:
        return render_template('main.html', error=model_error or 'Model is not ready. Run python prediction.py first.')

    user_data = {field: request.form.get(field, '').strip() for field in FEATURES}
    if any(not value or value == '----select option----' for value in user_data.values()):
        return render_template('main.html', error='Please complete all fields and select valid options.')

    try:
        values = [
            int(user_data['age']), int(user_data['sex']), int(user_data['cp']),
            int(user_data['trestbps']), int(user_data['chol']), int(user_data['fbs']),
            int(user_data['restecg']), int(user_data['thalach']), int(user_data['exang']),
            float(user_data['oldpeak']), int(user_data['slope']), int(user_data['ca']),
            int(user_data['thal']),
        ]
        data_scaled = scaler.transform(np.asarray([values], dtype=float))
        prediction_value = int(model.predict(data_scaled)[0])
        classes = list(model.classes_)
        positive_index = classes.index(1)
        risk_percentage = round(float(model.predict_proba(data_scaled)[0][positive_index]) * 100, 2)
    except (ValueError, TypeError, IndexError) as exc:
        return render_template('main.html', error=f'Invalid input or model data: {exc}')

    prediction_text = 'High Risk' if prediction_value == 1 else 'Low Risk'
    session['user_data'] = user_data
    session['prediction'] = prediction_text
    session['risk_percentage'] = risk_percentage
    return render_template('result.html', prediction=prediction_text, risk_percentage=risk_percentage)


@app.route('/download_report')
def download_report():
    user_data = session.get('user_data')
    if not user_data:
        return redirect(url_for('prediction'))
    pdf_buffer = generate_pdf(
        user_data,
        session.get('prediction', 'Unknown'),
        session.get('risk_percentage', 0),
    )
    response = make_response(pdf_buffer.getvalue())
    response.headers['Content-Type'] = 'application/pdf'
    response.headers['Content-Disposition'] = 'attachment; filename="Heart_Disease_Report.pdf"'
    response.headers['Cache-Control'] = 'no-cache'
    return response


def generate_pdf(user_data, prediction_text, risk_percentage):
    buffer = io.BytesIO()
    document = SimpleDocTemplate(buffer, pagesize=letter, title='Heart Disease Prediction Report')
    styles = getSampleStyleSheet()
    elements = [Paragraph('<b>Heart Disease Prediction Report</b>', styles['Title']), Spacer(1, 16)]
    summary = Table([['Prediction', 'Value'], ['Risk level', prediction_text], ['Model score', f'{risk_percentage}%']])
    summary.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.darkcyan),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
        ('PADDING', (0, 0), (-1, -1), 6),
    ]))
    elements.append(summary)
    elements.append(Spacer(1, 16))
    inputs = Table([['Input feature', 'Value']] + [[key, str(value)] for key, value in user_data.items()])
    inputs.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.darkcyan),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.grey),
        ('PADDING', (0, 0), (-1, -1), 5),
    ]))
    elements.extend([inputs, Spacer(1, 16)])
    elements.append(Paragraph(
        'Educational demonstration only. This result is not a diagnosis or medical advice; consult a qualified healthcare professional.',
        styles['Normal'],
    ))
    elements.append(Spacer(1, 10))
    elements.append(Paragraph(f'Report generated: {datetime.now():%Y-%m-%d %H:%M:%S}', styles['Normal']))
    document.build(elements)
    buffer.seek(0)
    return buffer


