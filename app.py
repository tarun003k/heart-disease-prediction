from datetime import datetime
import io
import os
import pickle
from pathlib import Path

import numpy as np
from flask import Flask, make_response, redirect, render_template, request, session, url_for
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / 'heart_disease_model.pkl'
SCALER_PATH = BASE_DIR / 'scaler.pkl'
FEATURES = [
    'age', 'sex', 'cp', 'trestbps', 'chol', 'fbs', 'restecg',
    'thalach', 'exang', 'oldpeak', 'slope', 'ca', 'thal',
]

app = Flask(__name__)
app.config['SECRET_KEY'] = os.environ.get('SECRET_KEY', 'local-development-only-change-before-deploying')

model = None
scaler = None
model_error = None


def load_model_artifacts():
    global model, scaler, model_error
    try:
        if not MODEL_PATH.is_file() or not SCALER_PATH.is_file():
            raise FileNotFoundError('Model artifacts are missing. Run `python prediction.py` first.')
        # Only load pickle files generated by this trusted project.
        with MODEL_PATH.open('rb') as f:
            model = pickle.load(f)
        with SCALER_PATH.open('rb') as f:
            scaler = pickle.load(f)
        model_error = None
    except (OSError, pickle.PickleError, EOFError, AttributeError, ImportError, ValueError) as exc:
        model = scaler = None
        model_error = str(exc)


load_model_artifacts()


